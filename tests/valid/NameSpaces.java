// Classes, fields, methods and variables live in separate namespaces.
class NameSpaces {
    public static void main(String[] args) {
        Item Item;
        Item = new Item();
        System.out.println(Item.Item(Item));
    }
}

class Item {
    Item Item;

    public int Item(Item other) {
        Item = other;
        return 1;
    }
}
